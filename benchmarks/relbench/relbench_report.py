"""``benchmarks/results/RESULTS.md`` from the result files of real runs (issue #65).

The table is computed from ``<results>/<dataset>/<task>/<method>_seed<n>.json`` and from nothing
else: no number is typed in, no published number is copied. A method with no ok result is shown as
skipped or failed with the reason the runs gave.
"""

from __future__ import annotations

import json
import statistics
from collections import defaultdict
from pathlib import Path
from typing import Any

from relbench_harness import METHODS

METRIC = "roc_auc"


def collect(results: Path) -> list[dict[str, Any]]:
    records = [json.loads(p.read_text()) for p in sorted(results.glob("*/*/*_seed*.json"))]
    if not records:
        raise FileNotFoundError(f"no result files under {results}")
    return records


def mean_std(values: list[float]) -> str:
    """``mean ± std`` (sample standard deviation); the std needs two or more seeds."""
    mean = statistics.fmean(values)
    return (
        f"{mean:.4f} ± {statistics.stdev(values):.4f}"
        if len(values) > 1
        else f"{mean:.4f} (1 seed)"
    )


def _seed(record: dict[str, Any]) -> int:
    return int(record["seed"])


def _row(method: str, runs: list[dict[str, Any]]) -> str:
    name = f"{method}: {METHODS.get(method, method)}"
    ok = [r for r in runs if r["status"] == "ok"]
    if not ok:
        why = sorted({r.get("reason") or r.get("error") or r["status"] for r in runs})
        return f"| {name} | {runs[0]['status']}: {'; '.join(why)} | | | | |"
    llm = [r["llm"] for r in ok if r.get("llm")]
    answered = [x for x in llm if x["answered"]]  # the stub's estimates are not a model's cost
    cost = f"${statistics.fmean(x['cost_usd_estimated'] for x in answered):.4f}" if answered else ""
    tokens = (
        f"{statistics.fmean(x['tokens_in_estimated'] + x['tokens_out_estimated'] for x in answered):.0f}"
        if answered
        else ""
    )
    models = sorted({m for x in llm for m in x["answered_by"]})
    note = ""
    if llm and not any(x["answered"] for x in llm):
        note = "no LLM answered (offline stub): no feature was proposed"
    elif llm:
        accepted = statistics.fmean(len(r["agent"]["accepted"]) for r in ok)
        note = f"{', '.join(models)}; {accepted:.1f} LLM features accepted per run"
    failed = len(runs) - len(ok)
    per_seed = ", ".join(f"{r['seed']}: {r['test'][METRIC]:.4f}" for r in sorted(ok, key=_seed))
    seeds = f"{len(ok)}" + (f" ok, {failed} not ok" if failed else "") + f" ({per_seed})"
    seconds = statistics.fmean(r["wall_seconds"]["total"] for r in ok)
    return (
        f"| {name} | {mean_std([r['test'][METRIC] for r in ok])} "
        f"| {mean_std([r['val'][METRIC] for r in ok])} | {seeds} | {seconds:.0f} s "
        f"| {cost} {('/ ' + tokens + ' tok') if tokens else ''} {note} |"
    )


def render(records: list[dict[str, Any]]) -> str:
    env = next(
        (r["environment"] for r in records if r["status"] == "ok"), records[0]["environment"]
    )
    lines = [
        "# Benchmark results",
        "",
        (
            "Generated by `benchmarks/relbench/run.py --aggregate` from the result files of real "
            "runs; nothing in this file is typed in."
        ),
        "",
        f"- RelBench {env['relbench']}, LightGBM {env['lightgbm']}, Python {env['python']}",
        f"- MLPilot commit {env['mlpilot_commit'] or 'unknown'}"
        + (f", CI run {env['ci_run']}" if env.get("ci_run") else ""),
        (
            f"- Test {METRIC.upper().replace('_', '-')} is RelBench's evaluator (`task.evaluate`) "
            "on the official test labels, read once per run. Val is the same evaluator on the "
            "validation rows (MLPilot stops its model early on them: not a held-out number)."
        ),
        (
            "- Mean ± sample standard deviation over seeds. Cost and tokens are the gateway's "
            "estimates (it counts words), per run."
        ),
        "",
    ]
    groups: dict[tuple[str, str], dict[str, list[dict[str, Any]]]] = defaultdict(
        lambda: defaultdict(list)
    )
    for r in records:
        groups[(r["dataset"], r["task"])][r["method"]].append(r)
    for (dataset, task), methods in sorted(groups.items()):
        lines += [
            f"## {dataset} / {task}",
            "",
            f"| Method | Test {METRIC.upper().replace('_', '-')} | Val | Seeds (test per seed) | Wall time | LLM |",
            "|---|---|---|---|---|---|",
            *(_row(m, methods[m]) for m in METHODS if m in methods),
            "",
        ]
    return "\n".join(lines)


def write(results: Path, out: Path) -> str:
    text = render(collect(results))
    out.write_text(text)
    return text
